    seekable_io = 102,
    dst_buffer_wrong = 104,
    src_buffer_wrong = 105,
    sequence_producer_failed = 106,
    external_sequences_invalid = 107,
};

/// The original's code for `err`, as `ZSTD_getErrorCode` gives it.
pub fn errorCode(err: Error) ErrorCode {
    return switch (err) {
        error.Generic => .generic,
        error.PrefixUnknown => .prefix_unknown,
        error.VersionUnsupported => .version_unsupported,
        error.FrameParameterUnsupported => .frame_parameter_unsupported,
        error.FrameParameterWindowTooLarge => .frame_parameter_window_too_large,
        error.CorruptionDetected => .corruption_detected,
        error.ChecksumWrong => .checksum_wrong,
        error.LiteralsHeaderWrong => .literals_header_wrong,
        error.DictionaryCorrupted => .dictionary_corrupted,
        error.DictionaryWrong => .dictionary_wrong,
        error.DictionaryCreationFailed => .dictionary_creation_failed,
        error.ParameterUnsupported => .parameter_unsupported,
        error.ParameterCombinationUnsupported => .parameter_combination_unsupported,
        error.ParameterOutOfBound => .parameter_out_of_bound,
        error.TableLogTooLarge => .table_log_too_large,
        error.MaxSymbolValueTooLarge => .max_symbol_value_too_large,
        error.MaxSymbolValueTooSmall => .max_symbol_value_too_small,
        error.CannotProduceUncompressedBlock => .cannot_produce_uncompressed_block,
        error.StabilityConditionNotRespected => .stability_condition_not_respected,
        error.StageWrong => .stage_wrong,
        error.InitMissing => .init_missing,
        error.MemoryAllocation => .memory_allocation,
        error.WorkSpaceTooSmall => .work_space_too_small,
        error.DstSizeTooSmall => .dst_size_too_small,
        error.SrcSizeWrong => .src_size_wrong,
        error.DstBufferNull => .dst_buffer_null,
        error.NoForwardProgressDestFull => .no_forward_progress_dest_full,
        error.NoForwardProgressInputEmpty => .no_forward_progress_input_empty,
        error.FrameIndexTooLarge => .frame_index_too_large,
        error.SeekableIO => .seekable_io,
        error.DstBufferWrong => .dst_buffer_wrong,
        error.SrcBufferWrong => .src_buffer_wrong,
        error.SequenceProducerFailed => .sequence_producer_failed,
        error.ExternalSequencesInvalid => .external_sequences_invalid,
    };
}
